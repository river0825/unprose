#!/usr/bin/env node
// scripts/resvg-pins.mjs [--check] — the prebuilt resvg natives a bundled canvas may download for PNG snapshots
// (packages/canvas/src/raster.ts, docs/canvas.md "Seeing the board"). Reads package-lock.json — the exact version,
// tarball URL and sha512 integrity of every @resvg/resvg-js-<platform> package — and writes
// packages/canvas/src/resvgPins.ts, which the canvas build (tsc) and the plugin bundle (scripts/bundle.mjs) carry.
// Run it after changing the @resvg/resvg-js version; `--check` exits 1 when the file is out of date (bundle.mjs and
// the tests check it too).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const PINS_FILE = path.join(root, 'packages/canvas/src/resvgPins.ts')

/** The pins file's text for a lockfile object. */
export function pinsSource(lock) {
  const pkgs = lock.packages ?? {}
  const main = pkgs['node_modules/@resvg/resvg-js']
  if (!main) throw new Error('package-lock.json has no node_modules/@resvg/resvg-js — run `npm install --save-optional @resvg/resvg-js -w @awd/canvas`')
  const natives = Object.entries(pkgs)
    .filter(([k]) => /^node_modules\/@resvg\/resvg-js-[a-z0-9-]+$/.test(k))
    .map(([k, v]) => ({ name: k.slice('node_modules/'.length), version: v.version, resolved: v.resolved, integrity: v.integrity, os: v.os ?? [], cpu: v.cpu ?? [], ...(v.libc ? { libc: v.libc } : {}) }))
    .filter((p) => p.version === main.version)
    .sort((a, b) => a.name.localeCompare(b.name))
  for (const p of natives) if (!/^sha512-/.test(p.integrity ?? '') || !p.resolved) throw new Error(`${p.name}: no sha512 integrity / resolved URL in package-lock.json`)
  const lines = natives.map((p) => `  ${JSON.stringify(p)},`)
  return [
    '// Generated by scripts/resvg-pins.mjs from package-lock.json — do not edit. The prebuilt resvg natives a canvas',
    '// without node_modules (the plugin bundle) may download for PNG snapshots, each pinned to its exact version and',
    '// sha512 integrity (src/raster.ts).',
    '',
    'export interface ResvgPin {',
    '  name: string',
    '  version: string',
    '  resolved: string',
    '  integrity: string',
    '  os: string[]',
    '  cpu: string[]',
    '  libc?: string[]',
    '}',
    '',
    `export const RESVG_VERSION = ${JSON.stringify(main.version)}`,
    '',
    'export const RESVG_PINS: ResvgPin[] = [',
    ...lines,
    ']',
    '',
  ].join('\n')
}

export function currentLock() {
  return JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = pinsSource(currentLock())
  const have = fs.existsSync(PINS_FILE) ? fs.readFileSync(PINS_FILE, 'utf8') : ''
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error('resvg-pins: packages/canvas/src/resvgPins.ts is out of date with package-lock.json — run `node scripts/resvg-pins.mjs`')
      process.exit(1)
    }
    console.log('resvg-pins: up to date')
  } else if (have === want) console.log('resvg-pins: up to date')
  else {
    fs.writeFileSync(PINS_FILE, want)
    console.log(`resvg-pins: wrote ${path.relative(root, PINS_FILE)}`)
  }
}
